def clean_pdf_column(text: str) -> str:
    lines = []
    for line in (text or "").splitlines():
        compact = clean_text(line)
        if not compact:
            continue
        if "전자문제집 CBT" in compact or compact.startswith("최강 자격"):
            continue
        if re.search(r"귀금속가공기능장\s+필기", compact):
            continue
        if re.match(r"\d+과목\s*:", compact):
            continue
        lines.append(compact)
    return "\n".join(lines)


def pdf_question_images(pdf, item: dict) -> dict[int, list[str]]:
    exam_id = int(item["examId"])
    mapped: dict[int, list[str]] = defaultdict(list)
    target_dir = root / "assets" / "jewelry" / item["key"] / str(exam_id)
    target_dir.mkdir(parents=True, exist_ok=True)
    image_index = 0

    for page in pdf.pages:
        half = page.width / 2
        for left, right in ((0, half), (half, page.width)):
            crop = page.crop((left, 0, right, page.height))
            markers = []
            for word in crop.extract_words(x_tolerance=1, y_tolerance=3):
                match = re.fullmatch(r"(\d{1,3})\.", word.get("text", ""))
                if match:
                    markers.append((float(word["top"]), int(match.group(1))))
            column_images = [
                value
                for value in page.images
                if left <= (float(value["x0"]) + float(value["x1"])) / 2 < right
            ]
            for value in column_images:
                previous = [
                    marker
                    for marker in markers
                    if marker[0] <= float(value["top"]) + 2
                ]
                if not previous:
                    continue
                number = max(previous, key=lambda marker: marker[0])[1]
                stream = value["stream"]
                attrs = stream.attrs
                width, height = map(int, value["srcsize"])
                raw = stream.rawdata
                decoded = stream.get_data()
                try:
                    if "DCTDecode" in str(attrs.get("Filter", "")):
                        image = Image.open(io.BytesIO(raw)).convert("RGB")
                    elif len(decoded) == width * height * 3:
                        image = Image.frombytes("RGB", (width, height), decoded)
                    elif len(decoded) == width * height:
                        image = Image.frombytes("L", (width, height), decoded)
                    else:
                        continue
                    image_index += 1
                    file_name = f"q{number}-figure-{image_index}.png"
                    output = target_dir / file_name
                    image.save(output, "PNG", optimize=True)
                    mapped[number].append(
                        f"assets/jewelry/{item['key']}/{exam_id}/{file_name}"
                    )
                except Exception:
                    continue
    return mapped


def parse_pdf_round(item: dict) -> tuple[dict, list[dict]]:
    exam_id = int(item["examId"])
    page_path = pdfs / item["file"]
    article_title = clean_text(item.get("articleTitle", ""))
    date_match = re.search(r"(20\d{2})년\s*(\d{2})월\s*(\d{2})일", article_title)
    if not date_match:
        raise ValueError(f"date missing in PDF article title: {article_title}")
    date = "".join(date_match.groups())
    session_match = re.search(r"\((\d+)회\)", article_title)
    session = f"{session_match.group(1)}회" if session_match else ""

    with pdfplumber.open(page_path) as pdf:
        ordered_columns = []
        for page in pdf.pages:
            half = page.width / 2
            for box in ((0, 0, half, page.height), (half, 0, page.width, page.height)):
                ordered_columns.append(
                    clean_pdf_column(
                        page.crop(box).extract_text(x_tolerance=1, y_tolerance=3)
                    )
                )
        combined = "\n".join(ordered_columns)
        image_map = pdf_question_images(pdf, item)

    question_matches = list(re.finditer(r"(?m)^(\d{1,3})\.\s+", combined))
    questions = []
    question_errors = []
    for index, match in enumerate(question_matches):
        source_number = int(match.group(1))
        end = question_matches[index + 1].start() if index + 1 < len(question_matches) else len(combined)
        segment = clean_text(combined[match.end():end])
        markers = list(re.finditer(f"[{choice_markers}]", segment))
        marker_numbers = [choice_number[value.group(0)] for value in markers]
        if len(markers) < 4 or marker_numbers[:4] != [1, 2, 3, 4]:
            question_errors.append(f"question {source_number}: four choices missing")
            continue
        markers = markers[:4]
        prompt = clean_text(segment[:markers[0].start()])
        choices = []
        for choice_index, marker in enumerate(markers):
            choice_end = markers[choice_index + 1].start() if choice_index < 3 else len(segment)
            choice_text = clean_text(segment[marker.end():choice_end])
            if not choice_text:
                break
            choices.append({
                "text": choice_text,
                "html": html_std.escape(choice_text).replace("\n", "<br>"),
                "images": [],
            })
        images = image_map.get(source_number, [])
        if (not prompt and not images) or len(choices) != 4:
            question_errors.append(f"question {source_number}: incomplete prompt or choices")
            continue
        answers = [
            choice_number[value.group(0)]
            for value in markers
            if value.group(0) in "❶❷❸❹"
        ]
        if len(answers) != 1:
            question_errors.append(f"question {source_number}: answer missing or ambiguous")
            continue
        source_subject = "귀금속가공기능장 종합"
        target_subject = target_subject_for(prompt, "")
        relevance = target_relevance_for(item["key"], prompt, "")
        if relevance == "peripheral":
            continue
        questions.append({
            "number": len(questions) + 1,
            "sourceNumber": source_number,
            "text": prompt,
            "html": html_std.escape(prompt).replace("\n", "<br>"),
            "images": images,
            "choices": choices,
            "answer": answers[0],
            "answerRate": None,
            "hint": "",
            "explanation": master_explanations.get(
                (exam_id, source_number),
                f"교사용 원문에서 {answers[0]}번이 정답으로 표시되어 있습니다."
            ),
            "explanationHtml": "",
            "explanationType": "ai-reference",
            "sourceSubject": source_subject,
            "targetSubject": target_subject,
            "targetRelevance": relevance,
            "source": item["url"],
        })

    if not questions:
        raise ValueError(
            f"no validated target-overlap questions in PDF: {'; '.join(question_errors[:5])}"
        )
    referenced_images = {
        Path(image_path).name
        for question in questions
        for image_path in question.get("images", [])
    }
    generated_dir = root / "assets" / "jewelry" / item["key"] / str(exam_id)
    if generated_dir.exists():
        for generated_image in generated_dir.glob("q*-figure-*.png"):
            if generated_image.name not in referenced_images:
                generated_image.unlink()
    source_count = len(question_matches)
    return {
        "id": f"jewelry-{item['key']}-{date}-{exam_id}",
        "examId": exam_id,
        "qualificationKey": item["key"],
        "qualification": item["name"],
        "shortQualification": item["shortName"],
        "kind": "jewelry-related",
        "sourceRole": item.get("role", "related"),
        "verification": "target-filtered",
        "sourceQuestionCount": source_count,
        "skippedQuestionCount": source_count - len(questions),
        "date": date,
        "sortKey": date,
        "year": int(date[:4]),
        "session": session,
        "title": re.sub(r"\s*-\s*귀금속가공기능장.*$", "", article_title),
        "subjects": ["귀금속가공기능장 종합"],
        "questions": questions,
        "examMinutes": round(len(questions) * 1.5),
        "source": item["url"],
        "categorySource": item["categoryUrl"],
    }, []


