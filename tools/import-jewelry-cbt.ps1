def choice_plain_text(choice: dict) -> str:
    return clean_text(choice.get("text") or re.sub(r"<[^>]+>", " ", choice.get("html", "")))


def reference_fact(prompt: str, answer_text: str) -> tuple[str, str]:
    negative = bool(re.search(
        r"아닌|옳지\s*않|틀린|잘못|거리가\s*먼|적합하지|해당하지",
        prompt,
    ))
    combined = f"{prompt} {answer_text}"
    if negative:
        for pattern, fact in reference_rules:
            if re.search(pattern, combined, flags=re.I):
                return fact, "concept"
    for pattern, fact in reference_rules:
        if answer_text and re.search(pattern, answer_text, flags=re.I):
            return fact, "concept"
    for pattern, fact in reference_rules:
        if re.search(pattern, prompt, flags=re.I):
            return fact, "concept"
    for pattern, fact in reference_rules:
        if re.search(pattern, combined, flags=re.I):
            return fact, "concept"
    return "", "subject"


def build_reference_explanation(question: dict) -> tuple[str, str]:
    prompt = clean_text(question.get("text", ""))
    answer_index = int(question["answer"]) - 1
    answer_choice = question["choices"][answer_index]
    answer_text = choice_plain_text(answer_choice)
    image_answer = not answer_text and bool(answer_choice.get("images"))

    if image_answer:
        for pattern, explanation in image_explanations:
            if re.search(pattern, prompt, flags=re.I):
                return explanation, "image"

    fact, basis = reference_fact(prompt, answer_text)
    if not fact:
        fact = (
            source_reference_notes.get(question.get("sourceSubject", ""))
            or subject_reference_notes.get(question.get("targetSubject", ""))
            or "문제의 조건과 각 보기의 정의를 대조해 해당 범주에 맞는지 판단해야 합니다."
        )

    short_answer = answer_text
    if len(short_answer) > 72:
        short_answer = short_answer[:69].rstrip() + "…"
    if image_answer:
        lead = "정답 그림은 문제에서 요구한 형상과 배치 조건을 만족합니다."
    elif re.search(r"아닌|옳지\s*않|틀린|잘못|거리가\s*먼|적합하지|해당하지", prompt):
        lead = f"문제에서 틀린 항목으로 고를 답은 '{short_answer}'입니다."
    elif re.search(r"얼마|몇\s*(?:%|배|도|개|면|g|그램|캐럿)|계산|구하|함량|비율", prompt):
        lead = f"주어진 값과 기준식을 적용한 결과는 '{short_answer}'입니다."
    elif re.search(r"순서|공정|단계|차례|먼저\s*해야|먼저\s*하는", prompt):
        lead = f"공정의 선후 관계를 적용하면 정답은 '{short_answer}' 순서입니다."
    else:
        lead = f"문제의 조건에 맞는 답은 '{short_answer}'입니다."

    if fact in lead:
        return lead, basis
    return f"{lead} {fact}", basis


def usable_source_explanation(value: str) -> bool:
    text = clean_text(value)
    if not text:
        return False
    if re.search(
        r"아래와 같은 오류 신고|오류신고 반론|추가 오류 신고|여러분들의 많은 의견|"
        r"\[관리자|정답\s*[①②③④1-4]번(?:입니다|으로)|맞는 것 인지 틀린 것 인지",
        text,
    ):
        return False
    without_author = re.sub(r"\[해설작성자\s*:[^\]]+\]", "", text).strip()
    return len(without_author) >= 24


def apply_reference_explanation(question: dict) -> None:
    source_explanation = clean_text(question.get("explanation", ""))
    if usable_source_explanation(source_explanation):
        return
    if source_explanation:
        question["sourceExplanation"] = source_explanation
    explanation, basis = build_reference_explanation(question)
    question["explanation"] = explanation
    question["explanationHtml"] = ""
    question["explanationType"] = "ai-reference"
    question["explanationBasis"] = basis


def target_subject_for(text: str, source_subject: str) -> str:
    haystack = f"{source_subject} {text}".lower()
    if any(word.lower() in haystack for word in diamond_words):
        return "다이아몬드 감정"
    if any(word.lower() in haystack for word in identification_words):
        return "보석 감별"
