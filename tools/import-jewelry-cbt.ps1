function Get-ExamIdsFromArticle {
    param(
        [string]$ArticleUrl,
        $Category
    )

    $ids = [System.Collections.Generic.HashSet[long]]::new()
    try {
        $html = (Invoke-CbtRequest -Uri $ArticleUrl).Content
        $articleId = [regex]::Match($ArticleUrl, '/(\d+)(?:\?.*)?$').Groups[1].Value
        if (-not $articleId) { $articleId = [Math]::Abs($ArticleUrl.GetHashCode()) }
        $articleFile = Join-Path $articlesDir "$($Category.key)`__$articleId.html"
        [System.IO.File]::WriteAllText($articleFile, $html, $utf8)
    }
    catch {
        Write-Warning $_
        return @()
    }
    foreach ($pattern in @('/cbt/exam/(\d+)/?', '/cbt/problem/(\d+)/', '\((\d{4,8})\)')) {
        foreach ($match in [regex]::Matches($html, $pattern, 'IgnoreCase')) {
            $value = [long]$match.Groups[1].Value
            if ($value -ge 1000) { [void]$ids.Add($value) }
        }
    }
    $seenPdfLinks = [System.Collections.Generic.HashSet[string]]::new()
    if ($Category.key -eq 'precious-master') {
    foreach ($match in [regex]::Matches($html, '<a\b[^>]*href\s*=\s*["'']([^"'']+)["''][^>]*>([\s\S]*?)</a>', 'IgnoreCase')) {
        $label = (ConvertTo-PlainText -Html $match.Groups[2].Value).Trim()
        if ($label -notmatch '교사용.*\.pdf$') { continue }
        $pdfUrl = Resolve-WebUrl -BaseUrl $ArticleUrl -Href $match.Groups[1].Value
        if (-not $pdfUrl -or -not $seenPdfLinks.Add($pdfUrl)) { continue }
        $pdfName = "$($Category.key)`__$articleId.pdf"
        $pdfTarget = Join-Path $pdfsDir $pdfName
        try {
            if ($Force -or -not (Test-Path -LiteralPath $pdfTarget) -or (Get-Item -LiteralPath $pdfTarget).Length -lt 10000) {
                Write-Host "  교사용 PDF 다운로드: $label"
                Invoke-WebRequest -Uri $pdfUrl -Headers $headers -UseBasicParsing -TimeoutSec 50 -OutFile $pdfTarget
            }
            if ((Get-Item -LiteralPath $pdfTarget).Length -lt 10000) {
                throw 'downloaded PDF is too small'
            }
            $script:teacherPdfItems.Add([ordered]@{
                key = $Category.key
                name = $Category.name
                shortName = $Category.shortName
                role = $Category.role
                allowRestoring = [bool]$Category.allowRestoring
                examId = [long]$articleId
                sourceType = 'pdf'
                url = $ArticleUrl
                file = $pdfName
                articleTitle = ([System.Net.WebUtility]::HtmlDecode(
                    [regex]::Match($html, '<meta\s+property=["'']og:title["'']\s+content=["'']([^"'']+)', 'IgnoreCase').Groups[1].Value
                ))
                categoryUrl = $Category.categoryUrl
            })
        }
        catch {
            Write-Warning "교사용 PDF 다운로드 실패: $pdfUrl : $_"
        }
        break
    }
    }
    return @($ids)
}

