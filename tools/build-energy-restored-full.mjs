// Publish only after every required image has a verified native upscale record.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { unresolvedNotes } from './energy-textbook-review.mjs';
const work='work/energy-restored-full';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const preservedBankHashes={
 energy:'3f0331ce8b779715ea96c8c5a0b6e723b345b45c539265a1eb6317f037dd3577',
 'energy-midterm':'5c0c1953885b07f06150ffab77b8f4dc61b87c39f2ce0d5e7c5e65beb8e3f4bd',
 'energy-textbook':'c9da9a0f1d3c9bd2408befe247ef58f56a59798f006e6a2baa3df74987315ba9',
};
for(const [key,value] of Object.entries(preservedBankHashes))assert.equal(sha(`data/${key}.js`),value,`Existing bank changed: ${key}`);
const manifest=read(`${work}/manifest.json`);
assert.equal(manifest.rows.length,1040);assert.deepEqual(manifest.errors,[]);
const images=read(`${work}/upscale-ledger.json`);
const geometry=read(`${work}/answer-geometry/staged.json`);
const reviewed=read(`${work}/answer-geometry/review.json`);
const oldBoxes=read('data/energy-textbook-hotspots.json');
const oldContext={window:{}};vm.runInNewContext(fs.readFileSync('data/energy.js','utf8'),oldContext);
const subjects=oldContext.window.CBT_DATA_ENERGY.rounds[0].subjects;
const rounds=[];const audit=[];
for(const q of manifest.rows){
 const key=`${q.year}-${q.session}`;
 let round=rounds.find(r=>r.id===`energy-industrial-restored-${key}`);
 if(!round){
  round={id:`energy-industrial-restored-${key}`,year:q.year,session:`${q.session}회`,
   sortKey:`${q.year}${String(q.session).padStart(2,'0')}99`,
   title:`에너지관리산업기사 ${q.year}년 ${q.session}회 CBT 복원문제 · 교재 원문`,
   subjects:[...subjects],kind:'textbook-restored',questions:[]};rounds.push(round);
 }
 for(const kind of ['question','explanation']){
  if(!q[kind+'Size'])continue;
  const row=images[`${q.key}-${kind}`];assert.ok(row,`Pending image: ${q.key}-${kind}`);
  assert.equal(sha(`${work}/original/${q.key}-${kind}.png`),row.sourceSha256);
  assert.equal(sha(row.asset),row.outputSha256);
  assert.deepEqual(row.outputSize,q[kind+'Size'].map(v=>v*2));
  assert.equal(row.tile,256);assert.equal(row.native,'arm64');
 }
 const sourceImage=images[`${q.key}-question`].asset;
 const boxes=geometry[q.key]||oldBoxes[sourceImage]||[];
 assert.ok(boxes.length===0||boxes.length===4,q.key);
 for(const b of boxes){assert.ok(b.width>0&&b.height>0&&b.x>=0&&b.y>=0&&b.x+b.width<=100.01&&b.y+b.height<=100.01,q.key);}
 const explanationImage=images[`${q.key}-explanation`]?.asset;
 const label=`${q.year}년 ${q.session}회 ${q.number}번`;
 round.questions.push({number:q.number,text:`에너지관리산업기사 ${label} · 교재 복원`,html:'',
  imageOnly:true,sourceImage,images:[],choices:Array.from({length:4},()=>({text:'',html:'',images:[]})),
  answer:q.answer,answerHotspots:boxes,explanation:[q.supplementalExplanation,unresolvedNotes[q.key]].filter(Boolean).join('\n\n'),
  explanationHtml:'',explanationImages:explanationImage?[explanationImage]:[],
  sourceSubject:subjects[Math.floor((q.number-1)/20)],sourceQualification:'에너지관리산업기사',
  sourcePage:`${label} · 교재 ${q.page+11}쪽`,visualSource:'교재 원문 스캔',
  explanationType:explanationImage?'textbook-original':'editorial-supplement',
  explanationProvenance:explanationImage?'printed-textbook-explanation-image':'printed-question-and-answer-supplement',
  explanationBasis:explanationImage?`교재 원문 해설 · 정답표 PDF ${q.answerPage}쪽 대조`:'교재에 별도 해설이 없는 문항의 보충 설명입니다. 정답은 해당 회차 교재 정답표 기준입니다.',
 });
 audit.push({key:q.key,pdfPage:q.page,answerTablePage:q.answerPage,answer:q.answer,
  sourceImage,explanationImage:explanationImage||null,hotspots:boxes.length,
  geometryReview:reviewed.find(r=>r.key===q.key)?.reason||'four-markers',
  questionSize:q.questionSize,explanationSize:q.explanationSize||null,parts:q.parts});
}
assert.equal(rounds.length,13);
for(const r of rounds){assert.equal(r.questions.length,80);assert.deepEqual(r.questions.map(q=>q.number),Array.from({length:80},(_,i)=>i+1));}
const catalog={key:'energy-restored',name:'에너지관리산업기사 교재 복원문제',shortName:'에너지관리',rounds};
fs.writeFileSync('data/energy-restored.js','// Generated by tools/build-energy-restored-full.mjs. Scan pixels, not OCR transcription.\nwindow.CBT_DATA_ENERGY_RESTORED = '+JSON.stringify(catalog,null,2)+';\n');
fs.writeFileSync('data/energy-restored-import-audit.json',JSON.stringify({date:'2026-10-28',sourceSha256:manifest.source.sha256,
 rounds:13,questions:1040,printedAnswerTables:13,printedAnswers:1040,
 geometryWithFourChoices:audit.filter(q=>q.hotspots===4).length,
 buttonFallback:audit.filter(q=>q.hotspots===0).map(q=>q.key),
 editorialSupplements:manifest.rows.filter(q=>q.supplementalExplanation).map(q=>q.key),
 preservedBanks:preservedBankHashes,
 images,rows:audit},null,2)+'\n');
console.log({rounds:rounds.length,questions:audit.length,imageSelect:audit.filter(q=>q.hotspots===4).length,fallback:audit.filter(q=>q.hotspots===0).length});
