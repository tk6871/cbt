"""Beginner algebra pages; uses the booklet's existing text and fraction drawing."""
from reportlab.platypus import PageBreak, KeepTogether


def build_algebra_primer(p, FractionFormula):
    story=[]

    def heading(title, intro):
        story.extend([p(title,'title'),p(intro,'small')])

    def block(title, explanation, equations=(), after=None):
        content=[p(title,'head'),p(explanation)]
        for equation in equations:
            content.append(FractionFormula(equation) if isinstance(equation,list) else p(equation,'formula'))
        if after: content.append(p(after))
        story.append(KeepTogether(content))

    def f(top,bottom):
        return {'top':[top] if isinstance(top,str) else top,'bottom':[bottom] if isinstance(bottom,str) else bottom}

    heading('식 읽기부터 · 글자는 숫자 자리','수학을 배웠다는 가정 없이 시작합니다. 지금은 공식을 외우지 말고 식을 한 문장씩 읽어보세요.')
    block('식과 등식은 무슨 뜻인가요?',
          '식은 숫자·글자·계산 기호로 양이나 계산을 나타낸 것입니다. 2+3도 식입니다. 2+3=5처럼 =로 두 값이 같다고 나타내면 등식이라고 합니다.',
          ['2 + 3 = 5'],
          '=는 “다음에 답이 나온다”보다 “양쪽 값이 같다”는 뜻입니다. 따라서 5=2+3으로 써도 맞습니다.')
    block('글자는 모르는 숫자가 들어갈 자리입니다',
          'x(엑스)는 아직 모르는 숫자의 이름입니다. Q나 G도 숫자 자리를 나타냅니다. 글자 자체를 곱하거나 더하라는 뜻은 아닙니다.',
          ['x + 3 = 8','x = 5'],
          'x 자리에 5를 넣으면 5+3=8입니다. 양쪽이 같으므로 맞는 답입니다. 이렇게 다시 넣어 확인하는 것을 검산이라고 합니다.')
    block('숫자를 넣는 것을 대입이라고 합니다',
          '공식은 같은 관계를 여러 문제에 쓰기 위해 글자로 적어둔 것입니다. A=B+C에서 B=2, C=3이라고 알려주면 그 글자 자리를 숫자로 바꿉니다.',
          ['A = B + C','A = 2 + 3 = 5'])
    block('붙어 있는 글자와 괄호 읽기',
          '3x는 3×x입니다. GcΔt는 G×c×Δt이고 Δt 전체가 “온도차”라는 하나의 값입니다. x라는 글자와 곱셈 기호 ×는 다릅니다. 2(t-5)는 2×(t-5)입니다.',
          ['Q = G × c × Δt'],
          '계산 순서는 괄호 안 → 곱하기·나누기 → 더하기·빼기입니다. 같은 순위는 왼쪽부터 합니다. 2+3×4=14, (2+3)×4=20입니다.')
    story.append(PageBreak())

    heading('이항의 원리 · 양쪽에 같은 계산','목표는 모르는 글자 x만 한쪽에 남기는 것입니다. 양팔저울처럼 양쪽에 같은 계산을 하면 같다는 관계가 유지됩니다.')
    block('더해진 수를 없애려면 양쪽에서 뺍니다',
          'x에 5를 더해 12가 됐습니다. x만 남기려고 양쪽에서 5를 뺍니다.',
          ['x + 5 = 12','x + 5 - 5 = 12 - 5','x = 7'],
          '중간 단계를 줄여 x=12-5라고 씁니다. +5가 반대편에서 -5로 보이는 이 정리를 이항이라고 합니다.')
    block('빼진 수를 없애려면 양쪽에 더합니다',
          'x에서 5를 뺀 결과가 12입니다. 양쪽에 5를 더하면 왼쪽의 -5와 +5가 없어집니다.',
          ['x - 5 = 12','x - 5 + 5 = 12 + 5','x = 17'])
    block('곱해진 수는 양쪽을 나눕니다',
          '3x는 3×x입니다. x를 세 번 모아 12가 됐으니 세 몫으로 나눕니다. 이때 3을 -3으로 바꾸는 것이 아닙니다.',
          ['3 × x = 12',['x = ',f('12','3'),' = 4']],
          '실제로는 양쪽을 3으로 나눈 것입니다. 왼쪽의 3÷3이 1이 되어 1×x=x만 남습니다.')
    block('나누어진 수는 양쪽에 곱합니다',
          'x를 3으로 나누니 4가 됐습니다. 양쪽에 3을 곱해 원래 양을 찾습니다.',
          [[f('x','3'),' = 4'],'x = 4 × 3 = 12'],
          '더하기 ↔ 빼기, 곱하기 ↔ 나누기는 서로 되돌리는 계산입니다. 0으로 나눌 수는 없습니다.')
    story.append(PageBreak())

    heading('분수와 COP · 아래의 글자 구하기','분수는 위(분자)를 아래(분모)로 나눈 것입니다. 분수선 위·아래 전체가 각각 한 묶음입니다.')
    block('분모가 여러 값이면 전체를 묶습니다',
          '아래의 2×3을 먼저 계산해 6을 만든 뒤, 24를 6으로 나눕니다.',
          [[f('24','2 × 3'),' = ',f('24','6'),' = 4']],
          '계산기에 24÷(2×3)으로 넣습니다. 24÷2×3은 왼쪽부터 12×3=36이므로 다른 계산입니다.')
    block('모르는 글자가 분모에 있으면?',
          '12÷x=4를 풀어봅시다. 분모 x는 0이 될 수 없습니다. 양쪽에 x를 곱하면 오른쪽은 4×x가 됩니다.',
          [[f('12','x'),' = 4'],'12 = 4 × x',['x = ',f('12','4'),' = 3']],
          '검산: 처음 식에 x=3을 넣으면 12÷3=4입니다. 분모의 x를 그냥 위로 올린 것이 아니라 양쪽에 같은 계산을 한 것입니다.')
    block('냉동 COP에서 입력동력 L을 구하기',
          'Qe는 냉동능력, L은 압축기에 넣는 동력, COP는 성능계수입니다. Qe=12 kW, COP=4이면 L을 구하는 식으로 바꿉니다.',
          [['COP = ',f('Qe','L')],'COP × L = Qe',['L = ',f('Qe','COP'),' = ',f('12','4'),' = 3 kW']],
          '양쪽에 L을 곱한 뒤, 양쪽을 COP로 나눴습니다. 단위는 kW÷단위 없는 4이므로 kW가 남습니다.')
    block('같은 공식도 구하는 것에 따라 모양이 달라집니다',
          '위의 Qe가 궁금하면 양쪽에 L을 곱한 단계에서 멈춥니다.',
          ['Qe = COP × L = 4 × 3 = 12 kW'],
          'COP 자체를 구할 때는 12 kW÷3 kW=4입니다. 이때만 같은 kW가 나뉘어 COP에는 단위가 없습니다.')
    story.append(PageBreak())

    heading('Q = G × c × Δt · G만 남겨봅시다','G를 구할 때는 G 옆에 곱해진 c와 Δt를 나누어 없앱니다. 글자를 무작정 반대편으로 옮기는 것이 아니라 양쪽에 같은 계산을 합니다.')
    block('공식의 글자를 먼저 읽습니다',
          'Q(큐)는 총열량[kJ], G(지)는 물의 질량[kg], c(씨)는 비열[kJ/(kg·℃)], Δt(델타 티)는 온도차[℃]입니다. 물의 양×물 1 kg을 1℃ 데우는 열×올릴 온도라는 뜻입니다.',
          ['Q = G × c × Δt'],
          'Δt는 Δ와 t를 따로 곱하는 것이 아니라 “온도차”라는 한 값입니다. 이 예제의 G는 총질량입니다. 흐르는 양 kg/s를 쓰는 문제에서는 Q도 열처리속도 kW로 맞춰야 합니다.')
    block('숫자를 아는 자리부터 채웁니다',
          '열량 Q=41.8 kJ, 물의 비열 c=4.18 kJ/(kg·℃), 온도차 Δt=5℃입니다. 물이 몇 kg인지 모르므로 G는 그대로 둡니다.',
          ['41.8 = G × 4.18 × 5','4.18 × 5 = 20.9','41.8 = G × 20.9'],
          '20.9는 새로 외울 상수가 아닙니다. 문제에서 아는 두 값 4.18과 5를 곱해서 만든 수입니다. 지금 식은 “물의 양에 20.9를 곱하니 41.8”이라는 뜻입니다.')
    block('양쪽을 20.9로 나누면 G만 남습니다',
          '곱하기 20.9를 되돌리는 계산은 나누기 20.9입니다. 오른쪽만 나누면 양쪽 값이 달라지므로 왼쪽도 똑같이 나눕니다.',
          [[f('41.8','20.9'),' = ',f('G × 20.9','20.9')],
           '20.9 ÷ 20.9 = 1 → 오른쪽은 G × 1 = G','2 = G → G = 2 kg'],
          '2=G와 G=2는 같은 말입니다. 양쪽 자리를 맞바꿔 읽었을 뿐, 분수의 위아래를 뒤집은 것이 아닙니다.')
    story.append(PageBreak())

    heading('G 구하기를 글자로 정리하면','방금 나눈 20.9는 c×Δt였습니다. 숫자 대신 글자를 써도 양쪽에 하는 계산은 같습니다.')
    block('G를 구하는 식이 이렇게 생기는 이유',
          'G만 남기려면 G 옆의 c×Δt로 양쪽을 나눕니다. c×Δt가 0이면 나눌 수 없으므로 이 방법으로 G를 정할 수 없습니다.',
          [[f('Q','c × Δt'),' = ',f('G × c × Δt','c × Δt')],
           ['G = ',f('Q','c × Δt'),' = ',f('41.8','4.18 × 5'),' = 2 kg']],
          '분모 전체가 c×Δt 한 묶음입니다. 계산기에는41.8÷(4.18×5)를 입력합니다. 41.8÷4.18×5는50이 되어 틀립니다. 괄호를 꼭 넣으세요.')
    block('답의 단위가 kg인 이유와 검산',
          '분모의 비열×온도차는 kJ/(kg·℃)×℃이므로 ℃가 나뉘어 kJ/kg가 남습니다. 총열량 kJ를 “1 kg당 필요한 열량” kJ/kg로 나누면 물의 양 kg가 됩니다.',
          [[f('kJ','kJ/kg'),' = kg'],'검산: 2 × 4.18 × 5 = 41.8 kJ'],
          '구한 G=2를 원래 Q=G×c×Δt에 다시 넣어 처음 열량41.8이 나오면 맞습니다.')
    block('온도차 Δt를 모른다면?',
          '이번에는 Δt만 남겨야 하므로 옆에 곱해진 G×c로 양쪽을 나눕니다. G=2 kg, c=4.18을 넣습니다.',
          [['Δt = ',f('Q','G × c'),' = ',f('41.8','2 × 4.18'),' = 5 °C']],
          '비열 c를 구한다면 c=Q÷(G×Δt)입니다. 외우기 전에 “구할 글자만 남기고 그 옆에 곱한 값 전체로 나눈다”를 떠올리세요.')
    block('온도차와 온도는 다릅니다',
          'Δt=높은 온도-낮은 온도입니다. 낮은 온도가 15℃이고 온도차가 5℃라면 높은 온도를 t라고 놓습니다.',
          ['5 = t - 15','5 + 15 = t','t = 20 °C'],
          '양쪽에 15를 더했습니다. 5℃ 올렸다는 말이 최종 온도 5℃라는 뜻은 아닙니다.')
    story.append(PageBreak())

    heading('BF·효율까지 · 식을 바꾼 뒤 확인','숫자를 넣기 전에 무엇을 구하는지 정합니다. 공식을 바꾸고 마지막에 원래 식으로 검산하세요.')
    block('BF에서 출구 온도 구하기',
          '입구 30℃, 코일 10℃, BF=0.4이고 출구 온도를 t라고 놓습니다. 먼저 분모의 30-10=20을 계산합니다.',
          [['0.4 = ',f('t − 10','30 − 10')],'0.4 × 20 = t - 10','8 + 10 = t','t = 18 °C'],
          '양쪽에 20을 곱한 뒤 양쪽에 10을 더했습니다. 검산: (18-10)÷(30-10)=8÷20=0.4입니다.')
    block('펌프에서 효율 η를 구한다면?',
          'η(에타)는 효율입니다. 여기서는 γQH를 한 덩어리 A라고 부르겠습니다. A는 문제에 새로 주어진 숫자가 아니라 γ×Q×H를 짧게 적은 이름입니다.',
          [['L = ',f('A','1,000 × η')],'1,000 × L × η = A',['η = ',f('A','1,000 × L'),' = ',f('γ × Q × H','1,000 × L')]],
          '양쪽에 1,000×η를 곱하고 양쪽을 1,000×L로 나눴습니다. 70%는 100개 중 70개라는 뜻으로 70÷100=0.7입니다. %로 물으면 마지막에 100을 곱합니다.')
    block('자주 틀리는 세 가지',
          '① 3x=12에서 x=12-3은 틀립니다. 곱해진 3은 나누어 없앱니다.\n② 12-x=4라면 양쪽에 x를 더해 12=4+x, 양쪽에서 4를 빼 x=8입니다. x 앞의 -를 놓치지 마세요.\n③ 괄호 전체를 계산합니다. (2+3)/3에서 더해진 +3만 지우면 안 됩니다.')
    block('혼자 확인 · 답은 바로 아래에',
          '연습 1: x+4=10\n연습 2: 5x=20\n연습 3: 18÷x=3',
          [],'정답: 연습 1은 x=6, 연습 2는 x=4, 연습 3은 x=6입니다. 각각 6+4=10, 5×4=20, 18÷6=3으로 검산합니다.')
    story.append(PageBreak())
    return story
