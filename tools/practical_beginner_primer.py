"""Numeric stories first, followed by the same equality using letters."""
from reportlab.platypus import PageBreak, KeepTogether


def build_algebra_primer(p, FractionFormula):
    story=[]
    def block(title, text, equations=(), after=''):
        items=[p(title,'head'),p(text)]
        for row in equations:
            items.append(FractionFormula(row) if isinstance(row,list) else p(row,'formula'))
        if after: items.append(p(after))
        story.append(KeepTogether(items))
    def f(top,bottom): return {'top':[top],'bottom':[bottom]}

    story.extend([p('계산을 처음 배운다면 · 숫자부터','title'),p('글자 공식은 뒤에서 연결합니다. 먼저 무엇을 합치고, 무엇을 나누는지 봅니다.')])
    block('더하기는 합치기, 빼기는 차이 찾기',
          '물에서 받은 열12와 압축기에 넣은 에너지3이 함께 나가면12+3=15입니다. 온도가20°C에서30°C로 올랐다면 오른 정도는30-20=10°C입니다. 어떤 숫자든 다 더하는 것이 아니라 같은 종류의 양을 합칩니다.')
    block('곱하기는 같은 양을 여러 번 더하기',
          '물1 kg을 데우는 열이20.9라면2 kg에는20.9+20.9가 필요합니다. 이를 짧게 쓰면20.9×2=41.8입니다. 2를 곱하는 이유는 물이 두 배이기 때문입니다.',
          ['1 kg → 20.9    /    2 kg → 41.8    /    3 kg → 62.7'])
    block('나누기는 한 개당 양 또는 필요한 개수 찾기',
          '사탕3개의 가격이12원이면 한 개는12÷3=4원입니다. 반대로 사탕 한 개가4원일 때12원으로 몇 개를 살 수 있는지도12÷4=3개로 구합니다. 무엇으로 나누느냐에 따라 답의 뜻이 달라집니다.',
          ['전체 열41.8 ÷ 물1 kg당 열20.9 = 물2 kg'],
          '물의 양을 찾으므로 “전체 열에1 kg당 열이 몇 번 들어 있나?”를 나눕니다. 2×20.9=41.8로 되넣어 확인할 수 있습니다.')
    block('소수와 %는 작은 양과 비율을 쓰는 방법',
          '0.5는 반, 0.1은10분의1입니다. 0.5 kg은 반 kg. 70%는 전체100 중70이니70÷100=0.7입니다. 전체10의70%는10×0.7=7입니다.',
          ['입력 × 0.7 = 전달된 양7 → 입력 = 7 ÷ 0.7 = 10'],
          '70%만 전달되어7이 되었다면 원래 양은7보다 커야 합니다. 원래 양을 되찾을 때0.7로 나눕니다. 20%를 더하라면 원래100%와 합쳐120%=1.2배입니다.')
    block('분수는 나누기를 위아래로 적은 것',
          '분수선 위의 수를 분자, 아래의 수를 분모라고 부릅니다. 아래 식은 모두12÷3=4라는 뜻입니다.',
          [[f('12','3'),' = 12 ÷ 3 = 4']],
          '분모1은 빈칸이 아닙니다. 12÷1=12라서12/1을12로 짧게 씁니다. 괄호는 한 묶음이니 먼저 계산합니다. 40÷(2×5)는40÷10=4입니다. 40÷2×5는 왼쪽부터 계산해100으로 달라집니다.')
    story.append(PageBreak())

    story.extend([p('물 데우기로 이해하는 글자식','title'),p('설명용 예제: 물을5°C 데우는 데 열41.8 kJ를 썼습니다. 물은 몇 kg일까요?')])
    block('먼저 물1 kg에 필요한 열을 알아봅니다',
          '비열4.18은 물1 kg을1°C 올리는 데 필요한 열[kJ]입니다. 5°C 올리려면4.18을 다섯 번 더하므로4.18×5=20.9 kJ입니다. 20.9는 물1 kg을5°C 데우는 열입니다.',
          ['물1 kg → 열20.9    /    물2 kg → 열41.8'],
          '실제로 쓴 열41.8은20.9의 두 배입니다. 따라서 물은2 kg입니다. 계산기로는41.8÷20.9=2입니다. 잠열도 전체 열670÷1 kg당 잠열335=2 kg처럼 같은 생각으로 풉니다.')
    block('G는 아직 모르는 물의 kg에 붙인 이름입니다',
          'Q는 전체 열, G는 물의 kg, c는 비열, Δt는 바뀐 온도입니다. Δt는 두 글자를 곱하는 것이 아니라 “온도차” 하나의 이름입니다. 아래 숫자식과 글자식은 같은 관계입니다.',
          ['전체 열 = 물의 kg × 1 kg당 필요한 열\n41.8 = G × 20.9\nQ = G × c × Δt'],
          'Q에41.8, c에4.18, Δt에5를 넣고 곱하면41.8=G×20.9입니다. 모르는 G만 글자로 둔 것입니다.')
    block('곱했던 수로 다시 나누면 처음 G로 돌아옵니다',
          '등호=는 양쪽이 같다는 표시입니다. 양쪽을 모두20.9로 나눠도 같다는 관계가 유지됩니다. 오른쪽은 G에20.9를 곱했다가 같은20.9로 나누는 셈입니다.',
          ['왼쪽: 41.8 ÷ 20.9 = 2\n오른쪽: (G × 20.9) ÷ 20.9 = G\n따라서 2 = G, 즉 G = 2 kg'],
          '20.9÷20.9=1이라 오른쪽은 G×1이 됩니다. 1을 곱해도 원래 값이니 G입니다. 1이 최종 답이라는 뜻은 아닙니다. 검산: 물2 kg×20.9=열41.8.')
    block('이번에는 비열 c를 모른다면?',
          '설명용으로 전체 열40 kJ, 물2 kg, 온도차5°C라고 합시다. 2×c×5는 c를10번 모은 양이니40=10×c입니다. c 하나는40÷10=4입니다.',
          [[f('Q','G × Δt'),' = ',f('G × c × Δt','G × Δt'),' = c  →  c = ',f('Q','G × Δt')]],
          '숫자로 했던40÷(2×5)를 글자로 쓴 것입니다. Q는 왼쪽 분자에 계속 있습니다. 마지막은 “4=c”를“c=4”라고 쓰듯 등호 양쪽 자리만 바꾼 것입니다. c의 단위는1 kg·1°C당 열인 kJ/(kg·°C)입니다.')
    story.append(PageBreak())

    story.extend([p('다른 식도 · 숫자의 뜻부터','title'),p('이항은 구할 값을 알아내도록 등호 양쪽에 같은 계산을 하는 정리입니다. 아래 숫자는 연습용입니다.')])
    block('COP · 몇 배인지 알 때 원래 동력 찾기',
          'COP4는 넣은 동력의4배만큼 냉동능력을 얻는다는 뜻입니다. 냉동능력이12 kW라면 “동력×4=12”. 원래 동력은12÷4=3 kW입니다. 3×4=12로 확인합니다.',
          [['COP = ',f('Qe','L'),' → COP × L = Qe → L = ',f('Qe','COP')]],
          'Qe는 냉동능력, L은 동력입니다. 분모 L을 없애려 양쪽에 L을 곱한 뒤, L 옆에 곱해진 COP로 양쪽을 나눴습니다. 숫자로는12÷4를 한 것입니다.')
    block('엔탈피 · 늘어난 양에서 끝의 값 찾기',
          '냉매1 kg의 처음 값이200이고 받은 열이100 kJ라면 끝의 값은200+100=300 kJ/kg입니다. 처음 값을 빼서 변화량을 구했던 계산을, 더하기로 되돌린 것입니다.',
          [[f('Qe','G'),' = h2 - h1 → ',f('Qe','G'),' + h1 = h2']],
          'h1은 처음, h2는 끝의 엔탈피입니다. 매초 냉매0.2 kg이 열20 kJ를 받았다면1 kg당 열은20÷0.2=100. 끝 값은100+200=300입니다. 1 kg당 열에 초당0.2 kg을 곱하면 원래20 kW로 돌아옵니다.')
    block('BF · 남은 온도차에 코일 온도 더하기',
          '입구30°C, 코일10°C면 전체 온도차는20°C입니다. BF0.4는 그 차이의40%가 남는다는 뜻이니20×0.4=8°C입니다. 출구는 코일10°C보다8°C 높아10+8=18°C입니다.',
          [['0.4 = ',f('t출구 - 10','20'),' → 0.4 × 20 = t출구 - 10']],
          '양쪽에20을 곱하면8=출구온도-10. 양쪽에10을 더하면18=출구온도입니다. 검산: (18-10)÷20=0.4. 10은 구한 숫자가 아니라 처음 주어진 코일 온도입니다.')
    block('제곱과 루트 · 배수에서 회전수 찾기',
          '2²는2×2=4, 2³은2×2×2=8입니다. √4는“같은 수를 두 번 곱해서4가 되는 양수”인2를 찾는 표시입니다. 계산기의 √ 키를 씁니다.',
          ['양정40 ÷ 원래 양정10 = 4배\n회전수 배수 = √4 = 2배\n원래1,000 rpm × 2 = 새 회전수2,000 rpm'],
          '같은 펌프의 상사조건에서 양정은 회전수 배수의 제곱으로 변합니다. 그래서 양정4배를 만드는 회전수는 루트로2배를 찾습니다. 회전수 자체를4배로 만드는 것이 아닙니다. 원래 양정10×2×2=40으로 확인합니다.')
    story.append(PageBreak())
    return story
