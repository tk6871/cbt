import assert from 'node:assert/strict';
import fs from 'node:fs';
import { practicalBatchOptions, restorePracticalBatch, restorePracticalMode } from '../src/cbt/practicalDisplay';
for (const n of [0,2,4,6,8,10,12]) assert.equal(restorePracticalBatch(String(n)),n);
for (const invalid of [null,'',' ','NaN','-1','3','1000']) assert.equal(restorePracticalBatch(invalid),2);
assert.equal(restorePracticalMode('handwrite'),'type');
assert.equal(restorePracticalMode('memorize'),'memorize');
assert.equal(restorePracticalMode('type'),'type');
const app=fs.readFileSync('src/cbt/App.vue','utf8');
assert.ok(!app.includes('PracticalAnswerPad') && !app.includes("value=\"handwrite\""));
assert.ok(app.includes('practicalBatchOptions'));
assert.ok(app.includes("localStorage.setItem('cbt-practical-layout', layout)"));
assert.ok(app.includes("localStorage.setItem('cbt-practical-batch-size', String(size))"));
assert.ok(app.indexOf('class="practical-answer-actions"')<app.indexOf('class="practical-solution"'));
assert.ok(app.indexOf('class="practical-solution"')<app.indexOf('class="practical-draft"'));
const css=fs.readFileSync('src/cbt/practicalWorkspace.css','utf8');
assert.ok(!css.includes('grid-template-columns: minmax(0,var(--practical-split'));
assert.ok(css.includes('.practical-cbt-layout .practical-question-grid { max-width:920px;'));
console.log(JSON.stringify({batchOptions:practicalBatchOptions,retiredHandwriteMigrates:true,settingsSaved:true,solutionBelowQuestion:true}));
