font = TTFont(fonts / "CBTStudySans-Regular.woff2", recalcTimestamp=False)
options = subset.Options()
options.name_IDs = ["*"]
options.name_languages = ["*"]
subsetter = subset.Subsetter(options=options)
home_chars = {ord(c) for c in text if ord(c) >= 32} | set(range(32, 127))
common_chars = set(font.getBestCmap())
subsetter.populate(unicodes=home_chars)
subsetter.subset(font)
names = {1: "CBT Home Sans", 3: "CBTHomeSans-Regular-v1", 4: "CBT Home Sans Regular",
         6: "CBTHomeSans-Regular", 16: "CBT Home Sans", 20: "CBTHomeSans-Regular"}
for record in font["name"].names:
    if record.nameID in names:
        record.string = names[record.nameID].encode(record.getEncoding())
font.save(fonts / "CBTHomeSans-Regular.woff2")

# Disjoint ranges let the browser skip the larger file for home labels and for
# icons that neither font contains. Uncommon Hangul still uses the original TTF.
def unicode_ranges(points):
    groups = []
    for point in sorted(points):
        if groups and groups[-1][1] + 1 == point:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ",".join(f"U+{a:X}-{b:X}" if a != b else f"U+{a:X}" for a, b in groups)


def face(filename, coverage, fmt="woff2"):
    return f'''@font-face {{
  font-family:"Nanum Gothic";
  src:url("./{filename}") format("{fmt}");
  unicode-range:{coverage};
  font-weight:400;
  font-display:swap;
}}
'''


css = "/* Generated by tools/build-home-ui-font.py. */" + chr(10)
css += face("NanumGothic-Regular.ttf", "U+AC00-D7A3", "truetype")
css += face("CBTStudySans-Regular.woff2", unicode_ranges(common_chars - home_chars))
css += face("CBTHomeSans-Regular.woff2", unicode_ranges(common_chars & home_chars))
(fonts / "study-ui.css").write_text(css)
